import { db } from "@/db/postgres";
import {
  transactionRepository as createTransactionRepository,
  TransactionRepositoryFactory
} from "@/features/transaction/db/transactionRepository";
import {
  InsertTransaction,
  SelectTransaction,
  insertTransactionSchema
} from "@/features/transaction/schemas/transactionSchema";
import { ZodError } from "zod";
import createNotificationUseCase, { CreateNotificationInput } from "@/usecases/notification/createNotificationUseCase";
// Assuming internalGetUserIdFromSession is the way to get current user for notification.
// This might be better passed in or handled by a higher-level service that orchestrates both.
import { internalGetUserIdFromSession } from "@/app/(admin)/notifications/actions"; // Temporary direct import

/**
 * Defines the input data structure for creating a new transaction.
 * It includes all necessary fields for a new transaction, such as description,
 * value, type, status, partner ID, date, and due date, while omitting
 * fields auto-generated by the database like 'id', 'createdAt', and 'updatedAt'.
 * This type is derived from the `InsertTransaction` schema.
 */
export type CreateTransactionInput = Omit<InsertTransaction, 'id' | 'createdAt' | 'updatedAt'>;

/**
 * @description Use case for creating a new transaction.
 * It validates the input data, persists the transaction using the repository,
 * and then fetches and returns the complete transaction object.
 *
 * @param {CreateTransactionInput} transactionData - The data for the new transaction.
 * @param {TransactionRepositoryFactory} [transactionRepoFactory=createTransactionRepository] - Optional factory for transaction repository.
 * @returns {Promise<SelectTransaction>} The created transaction.
 * @throws {ZodError} If input data validation fails.
 * @throws {Error} If there's an issue with the repository or other unexpected errors.
 */
export default async function createTransactionUseCase(
  transactionData: CreateTransactionInput,
  transactionRepoFactory: TransactionRepositoryFactory = createTransactionRepository
): Promise<SelectTransaction> {
  // 1. Validate input data
  const parsedData = insertTransactionSchema.parse(transactionData);

  const transactionRepo = transactionRepoFactory(db);

  // 2. Persist the transaction
  const { id: newId } = await transactionRepo.insert(parsedData);

  // 3. Fetch the complete transaction object
  const newTransaction = await transactionRepo.findById(newId);

  if (!newTransaction) {
    throw new Error("Failed to retrieve the created transaction after insertion.");
  }

  // 4. Attempt to create a notification (best effort)
  try {
    const currentUserId = await internalGetUserIdFromSession();
    if (currentUserId) {
      const notificationData: CreateNotificationInput = {
        userId: currentUserId,
        type: "new_transaction",
        message: `Nova transação "${newTransaction.description}" (${
          newTransaction.type === "E" ? "Entrada" : "Saída"
        }) no valor de ${newTransaction.value.toLocaleString("pt-BR", { style: "currency", currency: "BRL"})} foi criada.`,
        relatedEntityId: newTransaction.id,
        relatedEntityType: "transaction",
      };
      createNotificationUseCase(notificationData).catch(error => {
        console.error("Failed to create notification for new transaction:", error);
      });
    } else {
      console.warn("No user ID found to create notification for new transaction.");
    }
  } catch (error) {
    console.error(
      "Error during notification creation for new transaction:",
      error
    );
  }

  return newTransaction;
}
